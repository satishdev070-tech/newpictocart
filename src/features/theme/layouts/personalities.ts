/**
 * Layout personalities: one per store category ("layout family"). A personality lists the section
 * variants, header style and footer layout that suit the category, in order of preference, plus a
 * signature home-page composition for new stores of that category.
 *
 * Themes are given a layout by position: the n-th theme of an industry takes the n-th entry of
 * every list (wrapping), so themes in one category get different hero / grid / story / header /
 * footer combinations, and categories differ because their lists differ. A theme can still pin any
 * value in its own preset (explicit settings always win). Pure data.
 */

export type LayoutFamily = UnsplashCategory;
type Tone = "light" | "dark" | "accent" | "muted";

export type LayoutPersonality = {
  family: LayoutFamily;
  label: string;
  /** One-line description of the look (marketplace, AI builder prompts). */
  mood: string;
  hero: HeroVariant[];
  heroPanel: Tone[];
  products: ProductGridVariant[];
  categories: CategoryVariant[];
  /** CollectionGrid arrangements (subset of the category variants). */
  collections: ("grid" | "mosaic" | "rail")[];
  story: StoryVariant[];
  editorial: ("split" | "overlap" | "fullbleed" | "journal")[];
  testimonials: TestimonialVariant[];
  newsletter: NewsletterVariant[];
  usp: UspVariant[];
  header: HeaderStyle[];
  footer: FooterLayout[];
  /** Vertical rhythm for product sections. */
  spacing: SectionSpacing[];
  /** Default home page for a new store of this category (content slots as in the showcase stores). */
  signature: HomeItem[];
};

