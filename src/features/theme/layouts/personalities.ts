export const LAYOUT_PERSONALITIES: Readonly<Record<LayoutFamily, LayoutPersonality>> = P;

/** Layout family for a store industry slug or alias (unknown → general). */
export function layoutFamily(industry: string): LayoutFamily {
  return toUnsplashCategory(industry);
}

export function personalityFor(industry: string): LayoutPersonality {
  return P[layoutFamily(industry)];
}

/** Signature home page for a new store of this industry (copy; safe to mutate). */
export function signatureComposition(industry: string): HomeItem[] {
  return structuredClone(personalityFor(industry).signature);
}
